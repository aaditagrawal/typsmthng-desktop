//! Compatibility coverage for the maintained syntax-cache and YAML backports.
use std::io::{self, Write};
use syntect::dumps;
use syntect::highlighting::ThemeSet;
use syntect::parsing::{ParseState, ScopeStack, SyntaxDefinition, SyntaxSet, SyntaxSetBuilder};

fn parse(syntaxes: &SyntaxSet) -> Vec<String> {
    let syntax = syntaxes.find_syntax_by_extension("maintenance").unwrap();
    let mut state = ParseState::new(syntax);
    let mut stack = ScopeStack::new();
    let mut scopes = Vec::new();
    for line in ["let x = 42;\n", "fn f() { \"Café مرحبا\" }\n"] {
        for (_, operation) in state.parse_line(line, syntaxes).unwrap() {
            stack.apply(&operation).unwrap();
            scopes.push(format!("{stack:?}"));
        }
    }
    scopes
}

#[test]
fn legacy_cache_and_runtime_yaml_produce_the_same_scopes() {
    // Generated by unmodified syntect 5.3.0 / bincode 1.3.3, not this backport.
    let bytes = include_bytes!("fixtures/maintenance-v5.packdump");
    let cached: SyntaxSet = dumps::from_uncompressed_data(bytes).unwrap();
    let mut builder = SyntaxSetBuilder::new();
    builder.add(
        SyntaxDefinition::load_from_str(
            include_str!("fixtures/maintenance.sublime-syntax"),
            true,
            None,
        )
        .unwrap(),
    );
    let loaded = builder.build();
    let expected = parse(&cached);
    assert!(expected
        .iter()
        .any(|scope| scope.contains("keyword.control")));
    assert!(expected.iter().any(|scope| scope.contains("string.quoted")));
    assert_eq!(expected, parse(&loaded));

    let directory = tempfile::tempdir().unwrap();
    let path = directory.path().join("syntax.packdump");
    dumps::dump_to_uncompressed_file(&cached, &path).unwrap();
    assert_eq!(bytes.as_slice(), std::fs::read(&path).unwrap());
    let restored: SyntaxSet = dumps::from_uncompressed_dump_file(&path).unwrap();
    assert_eq!(expected, parse(&restored));
    let restored: SyntaxSet = dumps::from_reader(&dumps::dump_binary(&cached)[..]).unwrap();
    assert_eq!(expected, parse(&restored));
}

#[test]
fn bundled_legacy_syntax_and_theme_dumps_still_load() {
    let syntaxes = SyntaxSet::load_defaults_newlines();
    assert!(syntaxes.find_syntax_by_extension("rs").is_some());
    assert!(syntaxes.find_syntax_by_extension("yaml").is_some());
    let themes = ThemeSet::load_defaults();
    assert!(themes.themes.len() > 4);
    let restored: ThemeSet = dumps::from_reader(&dumps::dump_binary(&themes)[..]).unwrap();
    assert_eq!(
        themes.themes.keys().collect::<Vec<_>>(),
        restored.themes.keys().collect::<Vec<_>>()
    );
}

#[test]
fn yaml_syntax_errors_keep_the_original_source_location() {
    let error =
        SyntaxDefinition::load_from_str("name: bad\ncontexts: [\n", true, None).unwrap_err();
    match error {
        syntect::parsing::ParseSyntaxError::InvalidYaml(error) => {
            assert!(error.marker().line() >= 2);
        }
        other => panic!("expected YAML location, got {other}"),
    }
}

struct FlushFailure;

impl Write for FlushFailure {
    fn write(&mut self, bytes: &[u8]) -> io::Result<usize> {
        Ok(bytes.len())
    }

    fn flush(&mut self) -> io::Result<()> {
        Err(io::Error::other("fixture flush failure"))
    }
}

#[test]
fn cache_writes_report_flush_errors_and_truncated_input() {
    assert!(dumps::dump_to_writer(&"cache", FlushFailure).is_err());
    assert!(dumps::from_uncompressed_data::<SyntaxSet>(&[0xff, 0xff]).is_err());
    assert!(dumps::from_reader::<SyntaxSet, _>(&[0x78, 0x9c][..]).is_err());
}

#[test]
fn large_legacy_compatible_cache_values_round_trip() {
    // Bincode 1.3 accepted these. Do not inherit a replacement codec's smaller
    // default allocation ceiling and silently narrow the existing dump API.
    let value = "x".repeat(5 * 1024 * 1024);
    let encoded = dumps::dump_binary(&value);
    let decoded: String = dumps::from_reader(&encoded[..]).unwrap();
    assert_eq!(decoded, value);
}

